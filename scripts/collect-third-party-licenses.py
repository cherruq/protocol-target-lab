#!/usr/bin/env python3
"""Collect notices for locked Linux Rust dependencies and bundled Web code.

Requires prepared Cargo sources and frontend/node_modules; never downloads.
Run without flags after dependency changes, or --check to verify reproducibility.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
TARGET = 'x86_64-unknown-linux-gnu'
WEB_COMPONENTS = ('react', 'react-dom', 'scheduler', 'vite')
PREFIXES = ('license', 'licence', 'copying', 'copyright', 'notice', 'unlicense')


def digest(data):
    return hashlib.sha256(data).hexdigest()


def collect():
    metadata = json.loads(subprocess.check_output([
        'cargo', 'metadata', '--format-version', '1', '--locked', '--offline',
        '--filter-platform', TARGET,
    ], cwd=ROOT))
    nodes = {node['id']: node for node in metadata['resolve']['nodes']}
    seen, pending = set(), [metadata['resolve']['root']]
    while pending:
        item = pending.pop()
        if item not in seen:
            seen.add(item)
            pending.extend(nodes[item]['dependencies'])
    components, texts = [], {}

    def component(kind, name, version, license_id, source, directory, supplemental=False, license_file=None):
        files = sorted(p for p in directory.rglob('*')
                       if p.is_file() and p.name.lower().startswith(PREFIXES))
        if license_file:
            explicit = directory / license_file
            if not explicit.is_file():
                raise ValueError(f"Missing declared license_file for {name}: {license_file}")
            files = sorted(set(files + [explicit]))
        if supplemental:
            files = [ROOT / 'third-party/upstream/include_dir/LICENSE']
            provenance = json.loads((files[0].parent / 'source.json').read_text())
            vcs = json.loads((directory / '.cargo_vcs_info.json').read_text())
            if vcs['git']['sha1'] != provenance['commit']:
                raise ValueError(f'Supplemental upstream license revision differs from crate: {name}')
            if digest(files[0].read_bytes()) != provenance['sha256']:
                raise ValueError('supplemental license hash mismatch')
            source = provenance['url']
        if not files:
            raise ValueError(f'No license text found for {kind}:{name}@{version}')
        notices = []
        for path in files:
            content = path.read_text(encoding='utf-8').replace('\r\n', '\n')
            hash_id = digest(content.encode())
            texts[hash_id] = content
            relative = path.name if supplemental else path.relative_to(directory).as_posix()
            notices.append({'file': relative, 'sha256': hash_id})
        components.append({'kind': kind, 'name': name, 'version': version,
                           'declared_license': license_id, 'source': source, 'notices': notices})

    for package in sorted(metadata['packages'], key=lambda p: (p['name'], p['version'])):
        if package['id'] not in seen or package['source'] is None:
            continue
        component('cargo', package['name'], package['version'], package['license'],
                  package['repository'] or package['source'], Path(package['manifest_path']).parent,
                  package['name'] in ('include_dir', 'include_dir_macros'), package['license_file'])
    lock = json.loads((ROOT / 'frontend/package-lock.json').read_text())
    for name in WEB_COMPONENTS:
        package = lock['packages']['node_modules/' + name]
        directory = ROOT / 'frontend/node_modules' / name
        installed = json.loads((directory / 'package.json').read_text())
        if installed['version'] != package['version']:
            raise ValueError(f'Installed Web package differs from lockfile: {name}')
        component('npm', name, package['version'], package['license'], package['resolved'], directory)
    manifest = {'target': TARGET, 'scope': 'Rust Linux dependency closure (including build/proc macros); bundled React runtime and Vite notices',
                'lock_sha256': {name: digest((ROOT / name).read_bytes()) for name in
                                ('Cargo.lock', 'frontend/package-lock.json')}, 'components': components}
    output = ['Protocol Target Lab third-party license and copyright notices\n',
              'Generated by scripts/collect-third-party-licenses.py.\n',
              'Component index: third-party/licenses.json (included with the deb).\n\n']
    for item in components:
        output.append(f"{item['kind']}:{item['name']}@{item['version']} ({item['declared_license']})\n")
        output.append(f"Source: {item['source']}\n")
        output.extend(f"  {notice['file']}: SHA256 {notice['sha256']}\n" for notice in item['notices'])
    for hash_id, content in sorted(texts.items()):
        output.extend(['\n' + '=' * 72 + '\n', 'SHA256 ' + hash_id + '\n\n', content,
                       '' if content.endswith('\n') else '\n'])
    outputs = {'THIRD_PARTY_LICENSES.txt': ''.join(output).encode(),
               'third-party/licenses.json': (json.dumps(manifest, indent=2, ensure_ascii=False) + '\n').encode()}
    inputs = ['Cargo.lock', 'frontend/package-lock.json', 'scripts/collect-third-party-licenses.py',
              'third-party/upstream/include_dir/LICENSE', 'third-party/upstream/include_dir/source.json']
    hashes = {name: digest((ROOT / name).read_bytes()) for name in inputs}
    hashes.update({name: digest(data) for name, data in outputs.items()})
    outputs['third-party/license-inputs.sha256'] = ''.join(
        f'{hash_id}  {name}\n' for name, hash_id in sorted(hashes.items())).encode()
    return outputs, len(components), len(texts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs, components, notices = collect()
    for name, data in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f'Stale license inventory: {name}; rerun {Path(__file__).name}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f'{components} components, {notices} unique license/notice texts; ' +
          ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
